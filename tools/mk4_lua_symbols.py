#!/usr/bin/env python3
"""Emit the linked script labels and native IDs as a Lua table.

The Lua runtime prototype maps linked script addresses to Lua functions by
label name, so wordcode tables and native C callers can enter Lua scripts
without any change to the data package. Native IDs are the same stable
numbers the assembly sources use. This reads the project sources through the
linker and never reads an executable.
"""
import argparse
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mk4_link import link  # noqa: E402


def render(source):
    _, header, symbols = link(source)
    begin = int(re.search(r'#define SCRIPT_ADDRESS_BEGIN 0x([0-9a-f]+)u', header).group(1), 16)
    end = int(re.search(r'#define SCRIPT_ADDRESS_END 0x([0-9a-f]+)u', header).group(1), 16)
    labels = {name: value for name, value in symbols.items() if not name.startswith('MK4_')}
    scripts = {name: value for name, value in labels.items() if begin <= value < end}
    natives = {name: value for name, value in symbols.items() if name.startswith('MK4_NATIVE_')}
    layout = re.search(r'#define MK4_LAYOUT_ID "([^"]+)"', header).group(1).replace('\\x', '')
    lines = ['-- Generated by tools/mk4_lua_symbols.py from scripts/mk4/project.asm. Do not edit.',
             'return {', f'  layout = "{layout}",', '  scripts = {']
    lines += [f'    {name} = 0x{value:x},' for name, value in sorted(scripts.items())]
    lines += ['  },', '  labels = {']
    lines += [f'    {name} = 0x{value:x},' for name, value in sorted(labels.items())]
    lines += ['  },', '  natives = {']
    lines += [f'    {name} = 0x{value:x},' for name, value in sorted(natives.items())]
    lines += ['  },', '}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    try:
        text = render(args.source)
    except (OSError, ValueError, KeyError) as exc:
        parser.exit(1, str(exc) + '\n')
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_text() != text:
        args.output.write_text(text)


if __name__ == '__main__':
    main()
