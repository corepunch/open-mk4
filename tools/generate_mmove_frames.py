#!/usr/bin/env python3
"""Generate named Quake II-style frame tables for clips used by each fighter."""
import argparse
import re
from pathlib import Path

from retail_moves import RetailImage, clip_inventory
from c_format import format_c
from c_source import read_source, private_aliases


ROOT = Path(__file__).resolve().parents[1]
CHARACTER = re.compile(r"(?:static )?const MoveDef\s+(\w+)\s*=\s*\{([^;]+)\};", re.S)
CLIP_MEMBER = re.compile(r"\.clip\s*=\s*(\d+)")
POSITIONAL_CLIP = re.compile(r"^\s*(\d+)\s*,")
SCRIPT_CLIP = re.compile(r"mk4_(?:script|mmove)_(?:bind|bind_victim|inherit|scene_pose)\(fighter,\s*(\d+)\s*,")


def clip_names(character):
    source = read_source(ROOT / "game" / character / "character.c")
    names = {}
    aliases = {value: key for key, value in private_aliases(ROOT / 'game' / character / 'character.c').items()}
    for match in CHARACTER.finditer(source):
        symbol, body = match.groups()
        clip = CLIP_MEMBER.search(body)
        if clip is None:
            clip = POSITIONAL_CLIP.search(body)
        if clip is not None:
            names.setdefault(int(clip.group(1)), []).append(aliases.get(symbol, symbol))
    generated = ROOT / "game" / character / "generated/scripts.inc"
    if generated.exists():
        for match in SCRIPT_CLIP.finditer(generated.read_text()):
            names.setdefault(int(match.group(1)), [])
    return names


def identifier(value):
    return re.sub(r"[^a-zA-Z0-9_]", "_", value).lower()


def output_for(character, clips):
    names = clip_names(character)
    lines = [
        "/* Generated by tools/generate_mmove_frames.py; do not edit. */",
        "",
    ]
    for clip in sorted(names):
        if clip not in clips:
            raise ValueError("%s references absent clip %d" % (character, clip))
        count = clips[clip]["frame_count"]
        move = names[clip][0] if names[clip] else "clip_%03d" % clip
        stem = identifier("%s_%s" % (character, move))
        lines.extend([
            "static const int %s_samples[%d] = {%s};" %
            (stem, count * 2, ', '.join(str(frame) for frame in range(count) for _ in range(2))),
            "const mframe_t %s_frames[%d] = {{0}};" % (stem, count * 2),
            "const mmove_t %s_mmove = {.firstframe = 0, .lastframe = %d, .frame = %s_frames, .samples = %s_samples};" %
            (stem, count * 2 - 1, stem, stem),
            "",
        ])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--character", help="fighter name; defaults to all character folders")
    parser.add_argument("--archive", default=str(ROOT / "MK4/FILESYS.DAT"))
    parser.add_argument("--exe", default=str(ROOT / "MK4/MK-4.EXE"))
    parser.add_argument("--check", action="store_true", help="fail if generated output is stale")
    args = parser.parse_args()

    image = RetailImage(args.exe)
    clips = {row["id"]: row for row in clip_inventory(image, args.archive)}
    characters = [args.character] if args.character else sorted(path.parent.name for path in (ROOT / "game").glob("*/character.c"))
    errors = []
    for character in characters:
        source = ROOT / "game" / character / "character.c"
        if not source.is_file():
            errors.append("unknown character: " + character)
            continue
        target = ROOT / "game" / character / "generated/frames.inc"
        if '#include "generated/frames.inc"' not in source.read_text():
            if target.exists():
                if args.check:
                    errors.append("unused generated frame table: " + str(target.relative_to(ROOT)))
                else:
                    target.unlink()
            continue
        output = format_c(output_for(character, clips))
        if args.check:
            if not target.is_file() or target.read_text() != output:
                errors.append("missing or stale generated frame table: " + str(target.relative_to(ROOT)))
        else:
            target.write_text(output)
            print("%s: %d clips -> %s" % (character, len(clip_names(character)), target.relative_to(ROOT)))
    if errors:
        raise SystemExit("\n".join(errors))


if __name__ == "__main__":
    main()
