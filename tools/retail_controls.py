"""Compile reviewed command registrations from the typed retail input tables.

Only explicitly bound targets are emitted. The coverage audit reports every
unbound retail target, so a partial registration never claims a complete port.
Native addresses exist only in offline evidence, never in the runtime table.
"""
import argparse
from pathlib import Path
import sys

from character_catalog import character_id, CHARACTERS
from retail_moves import RetailImage
from retail_coverage import profile_for
from scorpion_moves import commands

ROOT = Path(__file__).resolve().parents[1]
TOKENS = {1: 'TOKEN_UP', 2: 'TOKEN_DOWN', 0xaa: 'TOKEN_BACK', 0xdd: 'TOKEN_FORWARD'}


def generate_controls(image, character, profile):
    bindings = profile.get('command_bindings', {})
    predicates = profile.get('command_predicates', {})
    rows = []
    for table in commands(image, character):
        if table.get('player'):
            raise ValueError('Player-specific command list needs an explicit portable slot gate')
        button = table['button']
        for record in table['records']:
            binding = bindings.get(record['target'])
            if binding is None:
                continue
            gate = record['predicate']
            if gate and gate not in predicates:
                raise ValueError('Unreviewed command predicate ' + gate)
            flags = int(record['flags'], 16) & 0x50
            if button.endswith('_release'):
                flags |= 0x100
            tokens = [TOKENS[token] for token in record['tokens']]
            rows.append('  {%s, {%s}, %d, %d, 0x%x, %s, %s},' % (
                'BUTTON_' + button.removesuffix('_release').upper(), ', '.join(tokens) or '0', len(tokens),
                record['window'], flags, predicates[gate] if gate else 'NULL', binding['symbol']))
    if not rows:
        raise ValueError('Reviewed command bindings produced no runtime entries')
    return ('/* Generated by tools/retail_controls.py; do not edit. */\n'
            '// clang-format off: Keep table entries on one row, including long rows.\n'
            'static const CommandDef retail_commands[] = {\n' + '\n'.join(rows) + '\n};\n// clang-format on\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--character', type=character_id, required=True)
    parser.add_argument('--exe', type=Path, default=ROOT / 'MK4/MK-4.EXE')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    profile = profile_for(args.character)
    if not profile or not profile.get('controls_output'):
        return 0
    try:
        output = generate_controls(RetailImage(args.exe), args.character, profile)
        path = ROOT / profile['controls_output']
        if args.check:
            if not path.is_file() or path.read_text() != output:
                raise ValueError('Generated command registrations differ: ' + str(path))
        else:
            path.write_text(output)
        return 0
    except (ValueError, OSError) as exc:
        print(str(exc), file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
