#!/usr/bin/env python3
"""Write the linked script section from the Lua script modules.

Scripts are Lua functions in `scripts/lua/`. Data tables, command lists,
reaction tables and native services still refer to a script by a linked
address, so every script function keeps one placeholder word in the script
section of the data package. The Lua runtime maps those addresses back to the
functions through `tools/mk4_lua_symbols.py`. No instruction words exist.
"""
import argparse
from pathlib import Path
import re

HEADER = ['; Generated by tools/mk4_script_labels.py from scripts/lua/program.lua. Do not edit.',
          '; One placeholder word per Lua script function keeps its linked address for',
          '; tables, command lists, reaction tables and native services.',
          '.section script']


def modules(program):
    text = program.read_text()
    names = re.findall(r'"([^"]+\.lua)"', text)
    if not names:
        raise ValueError(f'{program}: lists no modules')
    return [program.parent / name for name in names]


def labels(program):
    seen = []
    for module in modules(program):
        text = module.read_text()
        for name in re.findall(r'^function S\.([A-Za-z_]\w*)\(\)', text, re.M) + re.findall(r'^S\.([A-Za-z_]\w*) = S\.', text, re.M):
            if name in seen:
                raise ValueError(f'{module}: script {name} is defined twice')
            seen.append(name)
    return seen


def render(program):
    lines = list(HEADER)
    for name in labels(program):
        lines.append(f'{name}:')
        lines.append('  .word 0')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('program', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    try:
        text = render(args.program)
    except (OSError, ValueError) as exc:
        parser.exit(1, str(exc) + '\n')
    if not args.output.exists() or args.output.read_text() != text:
        args.output.write_text(text)


if __name__ == '__main__':
    main()
