#!/usr/bin/env python3
"""Optional original-x86 oracle for uninterrupted, no-contact high kicks.

Requires Unicorn. Runs the retail VM, callback stack and native recovery code.
Only pose submission, audio and contact queries are stubbed; contact explicitly
returns false. This is not a whole-game/clock-rate or collision oracle.
"""
import argparse
import json
from pathlib import Path
import struct
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'tools'))
from retail_moves import EXE_SHA256, RetailImage


def trace(image, character):
    from unicorn import Uc, UC_ARCH_X86, UC_MODE_32, UC_HOOK_CODE
    from unicorn.x86_const import UC_X86_REG_ESP, UC_X86_REG_EIP

    machine = Uc(UC_ARCH_X86, UC_MODE_32)
    machine.mem_map(0x400000, 0x1600000)
    for base, payload in image.sections:
        machine.mem_write(base, payload)

    def word(va, value):
        machine.mem_write(va, struct.pack('<I', value & 0xffffffff))

    def get(va):
        return struct.unpack('<I', machine.mem_read(va, 4))[0]

    for dst, value in image.fixups.items():
        word(dst, value)
    node, group, tick, done = 0x1000000, 0x1001000, 0, False
    for va, value in [(0x53c420, node // 4), (0x53c41c, group // 4),
                      (0x4d07ac, 0x1100000 // 4), (node + 4, 0x1101000 // 4),
                      (node + 0x34, character), (node + 0x3c, 0x1002000 // 4)]:
        word(va, value)
    poses, commands, contacts, frames = [], [], [], []

    def hook(machine, va, size, unused):
        nonlocal done
        if va == 0x46f650:
            done = True
            machine.emu_stop()
            return
        if va == 0x4594d6:
            commands.append(dict(step=tick, pc=hex(get(node + 0x48) * 4 - 4),
                                 word=hex(get(0x53c42c))))
        if va == 0x407920:
            poses.append(dict(step=tick, clip=image.clip(get(group + 0x24)),
                              frame=get(group + 0x28)))
        if va == 0x48d3f0:
            contacts.append(dict(step=tick, selector=get(0x53c42c)))
            word(0x53c44c, get(0x53c44c) & ~1)
        if va in (0x407920, 0x489f00, 0x48d3f0):
            sp = machine.reg_read(UC_X86_REG_ESP)
            machine.reg_write(UC_X86_REG_EIP, get(sp))
            machine.reg_write(UC_X86_REG_ESP, sp + 4)

    machine.hook_add(UC_HOOK_CODE, hook)

    def call(va, arguments=()):
        stack = 0x1800000
        machine.mem_write(stack, struct.pack('<%dI' % (len(arguments) + 1),
                                           0x1700000, *arguments))
        machine.reg_write(UC_X86_REG_ESP, stack)
        machine.emu_start(va, 0x1700000, count=100000)
        if not done:
            assert machine.reg_read(UC_X86_REG_EIP) == 0x1700000, 'Instruction budget exhausted'
            assert machine.reg_read(UC_X86_REG_ESP) == stack + 4, 'Unbalanced native call stack'

    call(0x459490, (0x4e5ca0,))
    for tick in range(100):
        if tick:
            word(0x53c22c, 0)
            call(get(node + 8))
        if done:
            break
        assert poses and poses[-1]['step'] == tick, 'No submitted pose for playback step'
        frames.append(poses[-1]['frame'])
    assert done, 'Move never returned to fighter controller'
    assert get(node + 4) == 0x1101000 // 4, 'Continuation stack did not unwind'
    return dict(character=character, clip=poses[0]['clip'], end_step=tick,
                displayed_frames=frames, pose_calls=poses, commands=commands,
                contact_queries=contacts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--exe', default='MK4/MK-4.EXE')
    parser.add_argument('--record', action='store_true', help='Regenerate reviewed JSON and C fixtures')
    args = parser.parse_args()
    image = RetailImage(args.exe)
    result = dict(exe_sha256=EXE_SHA256,
                  scenario='Uninterrupted high kick; no contact; one callback dispatch per step',
                  stubbed=['0x407920 pose submission', '0x489f00 sound',
                           '0x48d3f0 contact query (bit 0 cleared)'],
                  moves=[trace(image, character) for character in (0, 4)])
    directory = Path(__file__).parent / 'fixtures'
    fixture = directory / 'original_kicks.json'
    if args.record:
        fixture.write_text(json.dumps(result, indent=2) + '\n')
        rows = ['/* Generated by tests/verify_moves.py --record from original x86. */',
                '// clang-format off: Keep table entries on one row, including long rows.']
        for move in result['moves']:
            frames = ', '.join(map(str, move['displayed_frames']))
            rows.append('{%d, %d, %d, {%s}},' %
                        (move['character'], move['clip'], move['end_step'], frames))
        rows.append('// clang-format on')
        (directory / 'original_kicks.inc').write_text('\n'.join(rows) + '\n')
    else:
        assert result == json.loads(fixture.read_text()), 'Original playback fixture changed'
    print('PASS: original VM and native recovery; Scorpion 30 steps, Sub-Zero 29; balanced continuations')


if __name__ == '__main__':
    main()
